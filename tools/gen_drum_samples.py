"""Generate KIT SAMPLE's sounds from assets/samples-cc0/KIT as IMA ADPCM (4 bit, low nibble first).

    tools/gen_drum_samples.py OUT.h

The cuts, levels and rates follow SLOOP's tools/gen_samples.py (isod89). One sample per lane, in eng_drum.c DV_* order.
Most live in the resource region; the hats, which sound on nearly every step, stay in the image.
"""
import math
import sys
import wave
from pathlib import Path

KIT = Path(__file__).resolve().parents[1] / "assets" / "samples-cc0" / "KIT"
RATE = 22050
# lane: file, seconds kept, stored rate, dB under full scale, (hold s, tau s) of a shorter body, fade s, in the image
SOUNDS = [
    ("KICK", "10_kick_BDrumNew_hit_v5", 0.45, RATE, 0, (0.03, 0.13), 0.03, 0),
    ("SNARE", "11_snare_Snare2_HitSN_v7", 0.45, RATE, 0, None, 0.03, 0),
    ("CLAP", "13_clap_Clap_rr1", 0.45, RATE, 0, None, 0.03, 0),
    ("HATC", "14_hihat_HitC_v3", 0.45, 32000, -9, None, 0.03, 1),
    ("HATO", "15_ohat_HitO", 0.6, 32000, -9, None, 0.03, 1),
    ("TOM", "16_tomlo_TomL_HitS_v4", 0.45, RATE, 0, (0.04, 0.22), 0.03, 0),
    ("RIM", "12_rim_sidestick", 0.45, RATE, 0, None, 0.03, 0),
    ("BELL", "20_cowbell_Cowbell1_Normal_v3", 0.45, RATE, -4, None, 0.03, 0),
]
IMA_STEP = [7, 8, 9, 10, 11, 12, 13, 14, 16, 17, 19, 21, 23, 25, 28, 31, 34, 37, 41, 45, 50, 55, 60, 66, 73, 80, 88, 97,
            107, 118, 130, 143, 157, 173, 190, 209, 230, 253, 279, 307, 337, 371, 408, 449, 494, 544, 598, 658, 724, 796,
            876, 963, 1060, 1166, 1282, 1411, 1552, 1707, 1878, 2066, 2272, 2499, 2749, 3024, 3327, 3660, 4026, 4428,
            4871, 5358, 5894, 6484, 7132, 7845, 8630, 9493, 10442, 11487, 12635, 13899, 15289, 16818, 18500, 20350,
            22385, 24623, 27086, 29794, 32767]
IMA_IDX = [-1, -1, -1, -1, 2, 4, 6, 8]


def read_wav(path):
    with wave.open(str(path)) as w:
        if w.getsampwidth() != 2:
            raise SystemExit(f"gen_drum_samples: {path.name}: 16 bit WAV expected")
        n, ch, sr = w.getnframes(), w.getnchannels(), w.getframerate()
        raw = w.readframes(n)
    v = [int.from_bytes(raw[i:i + 2], "little", signed=True) / 32768 for i in range(0, len(raw), 2)]
    return sr, v if ch == 1 else [sum(v[i:i + ch]) / ch for i in range(0, len(v), ch)]


def resample(x, sr, to):
    """an average over the ratio, then linear interpolation"""
    k = int(round(sr / to))
    if k > 1:
        x = [sum(x[i:i + k]) / k for i in range(len(x))]
    out, p, step = [], 0.0, sr / to
    while p < len(x) - 1:
        i, f = int(p), p - int(p)
        out.append(x[i] * (1 - f) + x[i + 1] * f)
        p += step
    return out


def shape(x, rate, keep, db, body, fade):
    pk = max(map(abs, x))
    start = next(i for i, v in enumerate(x) if abs(v) > 0.02 * pk)
    x = x[max(0, start - 16):int(keep * rate) + max(0, start - 16)]
    if body:
        h = int(body[0] * rate)
        x = [v * (1.0 if i < h else math.exp(-(i - h) / (body[1] * rate))) for i, v in enumerate(x)]
    pk = max(map(abs, x))
    end = len(x)
    while end > 64 and abs(x[end - 1]) < 0.004 * pk:
        end -= 1
    x = x[:end]
    f = min(len(x) // 4, int(fade * rate))
    for i in range(f):
        x[len(x) - f + i] *= 1 - i / f
    g = 30000 / pk * 10 ** (db / 20)
    return [int(v * g) for v in x]


def encode(samples):
    pred, idx, out = 0, 0, []
    for x in samples:
        step, diff, code = IMA_STEP[idx], x - pred, 0
        if diff < 0:
            code, diff = 8, -diff
        vd = step >> 3
        for bit, s in ((4, step), (2, step >> 1), (1, step >> 2)):
            if diff >= s:
                code |= bit
                diff -= s
                vd += s
        pred = max(-32768, min(32767, pred - vd if code & 8 else pred + vd))
        idx = max(0, min(88, idx + IMA_IDX[code & 7]))
        out.append(code)
    if len(out) & 1:
        out.append(0)
    return bytes(out[i] | out[i + 1] << 4 for i in range(0, len(out), 2))


def rows(b, per=32):
    return "\n".join("    " + ",".join(map(str, b[i:i + per])) + "," for i in range(0, len(b), per))


def main(out):
    text = ["/* generated by tools/gen_drum_samples.py from assets/samples-cc0/KIT - do not edit */", "#pragma once",
            "#ifndef MELODEE_RES", "#define MELODEE_RES", "#endif"]
    table, flash, res = [], 0, 0
    for name, file, keep, rate, db, body, fade, image in SOUNDS:
        sr, x = read_wav(KIT / f"{file}.wav")
        x = shape(resample(x, sr, rate), rate, keep, db, body, fade)
        data = encode(x)
        text += [f"static const uint8_t SMPK_{name}[{len(data)}]{'' if image else ' MELODEE_RES'} = {{", rows(data), "};"]
        table.append(f"    {{SMPK_{name}, {len(x)}u, {rate}u, {0 if image else 1}u}},")
        flash += len(data) if image else 0
        res += 0 if image else len(data)
    text += ["static const smpk_t SMPK[DV_NLANE] = {", *table, "};", ""]
    Path(out).write_text("\n".join(text))
    print(f"drum samples: {len(SOUNDS)} sounds, {flash} B in the image, {res} B in resources -> {out}")


if __name__ == "__main__":
    main(sys.argv[1])
