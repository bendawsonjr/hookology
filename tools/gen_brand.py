"""(Hookology) the boot splash's mark and wordmark (run by tools/build.py generate()).

  gen_brand.py OUT.h [--png DIR]

The Hookology design system's mark (a quaver whose flag is a barbed fish-hook, on its 100-unit grid) and the wordmark
"hookology" in Unbounded SemiBold (assets/fonts/Unbounded[wght].ttf, SIL OFL 1.1), drawn 8x and box-filtered to 4-bit
alpha, then run-length coded: a byte (value << 4 | run - 1), runs of 1..16 pixels, rows back to back. The firmware tints
them (src/main.c splash_draw): the mark in track 1's colour, the wordmark in TEXT.

Output: BRAND_<N> (the runs), BRAND_<N>_W, _H, _LEN for N = MARK (108 units: 108 px box), WORD (30 px).
--png writes both as PNGs (white on black) to look at.
"""
import argparse
import math
import sys
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
UNBOUNDED = ROOT / "assets" / "fonts" / "Unbounded[wght].ttf"
SS = 8


def _cubic(p0, p1, p2, p3, n=32):
    return [tuple((1 - t) ** 3 * a + 3 * (1 - t) ** 2 * t * b + 3 * (1 - t) * t * t * c + t ** 3 * d
                  for a, b, c, d in zip(p0, p1, p2, p3)) for t in (i / n for i in range(n + 1))]


def _stroke(draw, pts, w, s):
    w = w * s
    for (x0, y0), (x1, y1) in zip(pts, pts[1:]):
        draw.line([(x0 * s, y0 * s), (x1 * s, y1 * s)], fill=255, width=max(1, round(w)))
    for x, y in pts:                                     # (round caps and joins)
        draw.ellipse([x * s - w / 2, y * s - w / 2, x * s + w / 2, y * s + w / 2], fill=255)


def mark(scale):
    """the mark on its 100-unit grid at scale px a unit -> an 'L' image (alpha)"""
    s = scale * SS
    im = Image.new("L", (round(100 * s), round(100 * s)), 0)
    d = ImageDraw.Draw(im)
    a = math.radians(-22)                                # the note head: an ellipse turned -22 degrees
    head = [(30 + 14 * math.cos(t) * math.cos(a) - 10.5 * math.sin(t) * math.sin(a),
             80 + 14 * math.cos(t) * math.sin(a) + 10.5 * math.sin(t) * math.cos(a))
            for t in (i * 2 * math.pi / 96 for i in range(96))]
    d.polygon([(x * s, y * s) for x, y in head], fill=255)
    bend = [(77 + 11 * math.cos(t), 54 + 11 * math.sin(t)) for t in (math.pi - i * math.pi / 24 for i in range(25))]
    stem = [(43, 78), (43, 10)] + _cubic((43, 10), (58, 14), (66, 24), (66, 38))[1:] + [(66, 54)] + bend[1:] + [(88, 44)]
    _stroke(d, stem, 8, s)
    _stroke(d, [(88, 44), (81, 52)], 6, s)
    return im


def word(text, px, wght=600):
    """text in Unbounded at px -> an 'L' image (alpha), drawn by FreeType (non-zero fill: the variable font's
    overlapping contours stay solid)"""
    from PIL import ImageFont
    f = ImageFont.truetype(str(UNBOUNDED), px * SS)
    f.set_variation_by_axes([wght])
    l, t, r, b = f.getbbox(text)
    im = Image.new("L", (r - l + 2 * SS, b - t + 2 * SS), 0)
    ImageDraw.Draw(im).text((SS - l, SS - t), text, font=f, fill=255)
    return im


def to4(im):
    """an 8x 'L' image -> (w, h, 4-bit values) box-filtered, cropped to its ink"""
    w, h = im.width // SS, im.height // SS
    im = im.crop((0, 0, w * SS, h * SS)).resize((w, h), Image.BOX)
    box = im.getbbox() or (0, 0, 1, 1)
    im = im.crop(box)
    px = [round(v * 15 / 255) for v in im.tobytes()]
    return im.width, im.height, px, box


def rle(px):
    out, i = [], 0
    while i < len(px):
        v, n = px[i], 1
        while i + n < len(px) and px[i + n] == v and n < 16:
            n += 1
        out.append(v << 4 | (n - 1))
        i += n
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("out")
    ap.add_argument("--png")
    a = ap.parse_args()
    lines = ["/* generated by tools/gen_brand.py: the boot splash's mark and wordmark, 4-bit alpha run-length coded */",
             "#pragma once", "#include <stdint.h>", ""]
    total = 0
    for name, im in (("MARK", mark(1.08)), ("WORD", word("hookology", 30))):
        w, h, px, box = to4(im)
        r = rle(px)
        total += len(r)
        lines += [f"#define BRAND_{name}_W {w}u", f"#define BRAND_{name}_H {h}u", f"#define BRAND_{name}_LEN {len(r)}u",
                  f"static const uint8_t BRAND_{name}[{len(r)}] = {{"]
        lines += ["    " + ", ".join(f"0x{b:02x}" for b in r[i:i + 16]) + "," for i in range(0, len(r), 16)]
        lines += ["};", ""]
        if a.png:
            Image.frombytes("L", (w, h), bytes(v * 17 for v in px)).save(Path(a.png) / f"brand_{name.lower()}.png")
        print(f"brand {name}: {w} x {h} px, {len(r)} B")
    Path(a.out).write_text("\n".join(lines))
    print(f"brand total {total} B -> {a.out}")


if __name__ == "__main__":
    sys.exit(main())
