"""Generate the HERA chord set tables from assets/hera/chordsets.json (from HERA by Ben Badio, data/chordsets.json).

    tools/gen_hera_chords.py OUT.h

100 sets x 12 chords. The notes stay in the image: the audio code reads them, and they must work without the
resource region. Names and genres are for the screen only, so they go in the resource region (MELODEE_RES).
"""
import json
import sys
from pathlib import Path

SRC = Path(__file__).resolve().parents[1] / "assets" / "hera" / "chordsets.json"
SETS, KEYS, SLOTS, NAME_MAX = 100, 12, 4, 12
NOTE = ("C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B")
INTERVAL = {5: "4th", 7: "5th", 12: "oct"}             # the stack sets (14..16): their list leaves the names empty


def name_of(c):
    n = c["notes"]
    return c["name"] or f"{NOTE[n[0] % 12]} {INTERVAL[n[1] - n[0]]}"


def check(sets):
    if [s["set"] for s in sets] != list(range(1, SETS + 1)):
        raise SystemExit("gen_hera_chords: the sets are not 1..100 in order")
    for s in sets:
        if [c["key"] for c in s["chords"]] != list(range(KEYS)):
            raise SystemExit(f"gen_hera_chords: set {s['set']}: the keys are not 0..11 in order")
        for c in s["chords"]:
            n = c["notes"]
            where = f"set {s['set']} key {c['key']}"
            if not 2 <= len(n) <= SLOTS or n != sorted(n) or not all(1 <= x <= 127 for x in n):
                raise SystemExit(f"gen_hera_chords: {where}: bad notes {n}")
            if not name_of(c).isascii() or not 1 <= len(name_of(c)) <= NAME_MAX:
                raise SystemExit(f"gen_hera_chords: {where}: bad name {c['name']!r}")


def pool(strings):
    blob, at = bytearray(), {}
    for s in strings:
        if s not in at:
            at[s] = len(blob)
            blob += s.encode() + b"\0"
    return blob, at


def rows(values, per=20):
    values = list(values)
    return "\n".join("    " + ",".join(map(str, values[i:i + per])) + "," for i in range(0, len(values), per))


def main(out):
    sets = json.loads(SRC.read_text())
    check(sets)
    genres, genre_at = pool(s["genre"] for s in sets)
    names, name_at = pool(name_of(c) for s in sets for c in s["chords"])
    genre_list = list(genre_at)
    notes = [n for s in sets for c in s["chords"] for n in (c["notes"] + [0] * SLOTS)[:SLOTS]]
    offs = [name_at[name_of(c)] for s in sets for c in s["chords"]]
    text = f"""/* generated by tools/gen_hera_chords.py from assets/hera/chordsets.json - do not edit */
#pragma once
#ifndef MELODEE_RES
#define MELODEE_RES
#endif
#define HERA_SETS {SETS}u
#define HERA_KEYS {KEYS}u
#define HERA_NAME_MAX {NAME_MAX}u
/* [set][key C..B][slot]: ascending, 0 in an unused slot */
static const uint8_t HERA_NOTES[HERA_SETS * HERA_KEYS * 4u] = {{
{rows(notes)}
}};
static const uint16_t HERA_NAME_OFF[HERA_SETS * HERA_KEYS] MELODEE_RES = {{
{rows(offs)}
}};
static const char HERA_NAMES[{len(names)}] MELODEE_RES = {{
{rows(names)}
}};
static const uint16_t HERA_GENRE_OFF[{len(genre_list)}] MELODEE_RES = {{
{rows(genre_at[g] for g in genre_list)}
}};
static const uint8_t HERA_GENRE[HERA_SETS] MELODEE_RES = {{
{rows(genre_list.index(s["genre"]) for s in sets)}
}};
static const char HERA_GENRES[{len(genres)}] MELODEE_RES = {{
{rows(genres)}
}};
"""
    Path(out).write_text(text)
    flash = len(notes)
    res = 2 * len(offs) + len(names) + 2 * len(genre_list) + SETS + len(genres)
    print(f"hera chords: {SETS} sets, {flash} B notes in the image, {res} B names in resources -> {out}")


if __name__ == "__main__":
    main(sys.argv[1])
